"""Pull the model out of the page so Node can test it.

Sections 1-6 of web/language-of-the-plume.html (maths, world, physical channel, reader model,
language evolution, smoke stage) have no DOM in them. This copies them verbatim into
plume_core.js with a CommonJS export line, so check_plume.js tests exactly the code the page runs.

    cd projects/language_of_the_plume && python core.py && node check_plume.js
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
PAGE = os.path.join(HERE, "..", "..", "web", "language-of-the-plume.html")
HEAD = "/* ====================================================================\n   {}"
EXPORTS = ("SmokeSim,F,WORLD,ENVS,hourToAng,angToHour,evaluate,BASELINE,PRIOR,PRIOR_M,STANDIN,Evolver,"
           "fitObserver,presence,feltOf,makeTrial,standInRespond,rng32,turb,smooth")

html = open(PAGE, encoding="utf-8").read()
js = re.search(r"<script>(.*)</script>", html, re.S).group(1)
a, b = js.index(HEAD.format("1. Maths")), js.index(HEAD.format("7. Drawing"))
with open("plume_core.js", "w", encoding="utf-8") as f:
    f.write('"use strict";\n// Generated by core.py from web/language-of-the-plume.html. Do not edit.\n')
    f.write(js[a:b])
    f.write("\nmodule.exports={%s};\n" % EXPORTS)
print("plume_core.js:", b - a, "chars of model code")
